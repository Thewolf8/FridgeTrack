let currentLang = localStorage.getItem('fridgetrack-language') || 'system';

function detectSystemLanguage() {
  const lang = navigator.language || navigator.userLanguage || 'en';
  if (lang.startsWith('ar')) return 'ar';
  if (lang.startsWith('fr')) return 'fr';
  return 'en';
}

export function getCurrentLanguage() {
  if (currentLang === 'system') {
    return detectSystemLanguage();
  }
  return currentLang;
}

export function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('fridgetrack-language', lang);
  const effectiveLang = lang === 'system' ? detectSystemLanguage() : lang;
  document.documentElement.dir = effectiveLang === 'ar' ? 'rtl' : 'ltr';
  document.documentElement.lang = effectiveLang;
}

export function t(key, replacements = {}) {
  const lang = getCurrentLanguage();
  const dict = translations[lang] || translations.en;
  let text = dict[key] || translations.en[key] || key;
  Object.entries(replacements).forEach(([k, v]) => {
    text = text.replace(`{${k}}`, v);
  });
  return text;
}

